function getGameData(locale: Locale): GameInfo[] {
  return gamesMap[locale] || zhGames;
}

export function getGames(locale?: Locale): GameInfo[] {
  return getGameData(locale || 'zh');
}

export function getGamesByCategory(category: string, locale?: Locale): GameInfo[] {
  return getGameData(locale || 'zh').filter((g) => g.category === category);
}

export function getFeaturedGames(locale?: Locale): GameInfo[] {
  return getGameData(locale || 'zh').slice(0, 4);
}
