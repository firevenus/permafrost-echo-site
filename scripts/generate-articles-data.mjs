/**
 * Build-time script: reads markdown articles and generates static TypeScript data.
 * This avoids using Node.js fs/path at Edge Runtime.
 * Run: node scripts/generate-articles-data.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const contentDir = path.join(root, 'content');
const outputDir = path.join(root, 'src', 'lib');

const locales = fs.readdirSync(contentDir).filter((f) => {
  const full = path.join(contentDir, f);
  return fs.statSync(full).isDirectory();
});

const allArticles = {};
const allSlugs = {};

for (const locale of locales) {
  const articlesDir = path.join(contentDir, locale, 'articles');
  if (!fs.existsSync(articlesDir)) continue;

  const filenames = fs
    .readdirSync(articlesDir)
    .filter((f) => f.endsWith('.md'));

  const articles = filenames
    .map((filename) => {
      const slug = filename.replace(/\.md$/, '');
      const filePath = path.join(articlesDir, filename);
      const fileContents = fs.readFileSync(filePath, 'utf8');
      const { data, content } = matter(fileContents);

      return {
        slug,
        title: data.title || slug,
        date: typeof data.date === 'object'
          ? data.date.toISOString().split('T')[0]
          : data.date || '',
        excerpt: data.excerpt || '',
        cover: data.cover || undefined,
        tags: data.tags || [],
        author: data.author || undefined,
        content,
      };
    })
    .sort((a, b) => (a.date > b.date ? -1 : 1));

  allArticles[locale] = articles;
  allSlugs[locale] = articles.map((a) => a.slug);
}

// Generate TypeScript data file
const tsContent = `// Auto-generated by scripts/generate-articles-data.mjs — DO NOT EDIT
// Generated at: ${new Date().toISOString()}

export interface ArticleMeta {
  slug: string;
  title: string;
  date: string;
  excerpt: string;
  cover?: string;
  tags: string[];
  author?: string;
}

export interface Article extends ArticleMeta {
  content: string;
}

export const articlesData: Record<string, Article[]> = ${JSON.stringify(allArticles, null, 2)};

export const articleSlugs: Record<string, string[]> = ${JSON.stringify(allSlugs)};

export function getArticles(locale: string): ArticleMeta[] {
  return (articlesData[locale] || []).map(({ content, ...meta }) => meta);
}

export function getArticleBySlug(locale: string, slug: string): Article | null {
  return articlesData[locale]?.find((a) => a.slug === slug) || null;
}

export function getAllArticleSlugs(locale: string): string[] {
  return articleSlugs[locale] || [];
}
`;

// Write to src/lib/articles-data.ts
const outputPath = path.join(outputDir, 'articles-data.ts');
fs.writeFileSync(outputPath, tsContent, 'utf8');
console.log(`✅ Generated ${outputPath}`);
console.log(`   Locales: ${Object.keys(allArticles).join(', ')}`);
console.log(`   Total articles: ${Object.values(allArticles).reduce((sum, arr) => sum + arr.length, 0)}`);
