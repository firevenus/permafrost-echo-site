import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const root = process.cwd();
const contentRoot = path.join(root, 'content');
const outputPath = path.join(root, 'src', 'lib', 'articles-data.ts');
const locales = ['zh', 'en', 'ja', 'ko', 'ru', 'mn'];

const articlesByLocale = Object.fromEntries(
  locales.map((locale) => {
    const articleDirectory = path.join(contentRoot, locale, 'articles');
    const articles = fs.existsSync(articleDirectory)
      ? fs
          .readdirSync(articleDirectory)
          .filter((file) => file.endsWith('.md'))
          .map((file) => {
            const slug = file.replace(/\.md$/, '');
            const source = fs.readFileSync(path.join(articleDirectory, file), 'utf8');
            const parsed = matter(source);
            return {
              slug,
              title: String(parsed.data.title || slug),
              date: parsed.data.date instanceof Date
                ? parsed.data.date.toISOString().slice(0, 10)
                : String(parsed.data.date || ''),
              excerpt: String(parsed.data.excerpt || ''),
              tags: Array.isArray(parsed.data.tags) ? parsed.data.tags.map(String) : [],
              author: parsed.data.author ? String(parsed.data.author) : undefined,
              content: parsed.content.trim(),
            };
          })
          .sort((a, b) => b.date.localeCompare(a.date))
      : [];
    return [locale, articles];
  })
);

const generated = `// Generated by scripts/generate-articles-data.mjs. Do not edit by hand.\n\n` +
`export interface ArticleInfo {\n` +
`  slug: string;\n` +
`  title: string;\n` +
`  date: string;\n` +
`  excerpt: string;\n` +
`  tags: string[];\n` +
`  author?: string;\n` +
`  content: string;\n` +
`}\n\n` +
`const articlesByLocale: Record<string, ArticleInfo[]> = ${JSON.stringify(articlesByLocale, null, 2)};\n\n` +
`export const articleSlugs: Record<string, string[]> = Object.fromEntries(\n` +
`  Object.entries(articlesByLocale).map(([locale, articles]) => [\n` +
`    locale,\n` +
`    articles.map((article) => article.slug),\n` +
`  ]),\n` +
`);\n\n` +
`export function getArticles(locale: string): ArticleInfo[] {\n` +
`  return articlesByLocale[locale] || [];\n` +
`}\n\n` +
`export function getArticleBySlug(locale: string, slug: string): ArticleInfo | undefined {\n` +
`  return getArticles(locale).find((article) => article.slug === slug);\n` +
`}\n`;

fs.writeFileSync(outputPath, generated, 'utf8');
console.log(`Generated ${outputPath}`);
